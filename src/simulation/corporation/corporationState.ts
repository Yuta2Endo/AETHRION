/**
 * Creates the empty corporation state — no player corporation exists until
 * the player establishes one.
 */
export function createInitialCorporationState(): CorporationState {
  return {
    corporations: [],
    playerCorporationId: null,
    tick: 0,
  };
}

/**
 * Validates a corporation record.
 * Invalid records are rejected before they can corrupt the simulation.
 */
export function isValidCorporation(corporation: Corporation): boolean {
  if (!corporation || typeof corporation.id !== 'string' || corporation.id.length === 0) {
    return false;
  }
  if (typeof corporation.name !== 'string' || corporation.name.trim().length === 0) {
    return false;
  }
  if (!isFiniteNumber(corporation.foundedAtSimMs) || corporation.foundedAtSimMs < 0) {
    return false;
  }
  if (!getCorporationTier(corporation.tierId)) return false;
  if (!isFiniteNumber(corporation.level) || corporation.level < 1) return false;
  if (!isFiniteNumber(corporation.reputation) || corporation.reputation < 0 || corporation.reputation > 100) {
    return false;
  }
  if (!isFiniteNumber(corporation.missedPayrollCount) || corporation.missedPayrollCount < 0) {
    return false;
  }
  if (!isFiniteNumber(corporation.transactionSequence) || corporation.transactionSequence < 0) {
    return false;
  }
  if (corporation.lastPayrollPeriodId !== null && typeof corporation.lastPayrollPeriodId !== 'string') {
    return false;
  }

  const { finances } = corporation;
  if (!finances) return false;
  if (!isFiniteNumber(finances.balance) || finances.balance < 0) return false;
  if (!isFiniteNumber(finances.lifetimeRevenue) || finances.lifetimeRevenue < 0) return false;
  if (!isFiniteNumber(finances.lifetimeOperatingExpenses) || finances.lifetimeOperatingExpenses < 0) {
    return false;
  }
  if (!isFiniteNumber(finances.lifetimePayrollExpenses) || finances.lifetimePayrollExpenses < 0) {
    return false;
  }
  if (!isFiniteNumber(finances.lifetimeHiringCosts) || finances.lifetimeHiringCosts < 0) return false;
  if (!isFiniteNumber(finances.periodRevenue) || finances.periodRevenue < 0) return false;
  if (!isFiniteNumber(finances.periodOperatingExpenses) || finances.periodOperatingExpenses < 0) {
    return false;
  }
  if (!isFiniteNumber(finances.periodPayrollExpenses) || finances.periodPayrollExpenses < 0) {
    return false;
  }

  if (!Array.isArray(corporation.transactions)) return false;
  if (corporation.transactions.length > MAX_TRANSACTIONS) return false;
  for (const transaction of corporation.transactions) {
    if (!transaction || typeof transaction.id !== 'string' || transaction.id.length === 0) return false;
    if (!isFiniteNumber(transaction.amount)) return false;
    if (!isFiniteNumber(transaction.balanceAfter) || transaction.balanceAfter < 0) return false;
    if (!isFiniteNumber(transaction.simTimeMs)) return false;
  }

  if (!Array.isArray(corporation.financialHistory)) return false;
  if (corporation.financialHistory.length > MAX_FINANCIAL_HISTORY) return false;
  for (const snapshot of corporation.financialHistory) {
    if (!snapshot || typeof snapshot.periodId !== 'string') return false;
    if (!isFiniteNumber(snapshot.netProfit)) return false;
    if (!isFiniteNumber(snapshot.balance) || snapshot.balance < 0) return false;
  }

  return true;
}

/**
 * Validates the whole corporation state, including id uniqueness.
 */
export function isValidCorporationState(state: CorporationState): boolean {
  if (!state || !Array.isArray(state.corporations)) return false;
  if (!isFiniteNumber(state.tick) || state.tick < 0) return false;

  const ids = new Set<CorporationId>();
  for (const corporation of state.corporations) {
    if (!isValidCorporation(corporation)) return false;
    if (ids.has(corporation.id)) return false;
    ids.add(corporation.id);
  }

  if (state.playerCorporationId !== null) {
    if (!ids.has(state.playerCorporationId)) return false;
  }

  return true;
}

/**
 * Finds a corporation by its stable identifier.
 */
export function findCorporation(
  state: CorporationState,
  id: CorporationId,
): Corporation | undefined {
  return state.corporations.find((corporation) => corporation.id === id);
}

/**
 * Returns the player corporation, or null when none has been established.
 */
export function getPlayerCorporation(state: CorporationState): Corporation | null {
  if (state.playerCorporationId === null) return null;
  return findCorporation(state, state.playerCorporationId) ?? null;
}
