/**
 * Corporation Engine — data model.
 *
 * Owns the corporation record, its organisational structure, its financial
 * ledger and its progression. The Employee Engine owns the employee records;
 * headcount and workforce statistics are **derived**, never duplicated here.
 */

import { isFiniteNumber } from '@/core/utils';
import { DEPARTMENTS, type DepartmentId } from '@/simulation/contracts';

export type CorporationId = string;
export type CorporationTierId = string;

/**
 * Operational state of the corporation.
 * - active    : trading normally
 * - thriving  : profitable with a healthy balance
 * - strained  : losses, low reputation or a missed payroll
 * - insolvent : the balance cannot cover the operating costs
 */
export type CorporationStatus = 'active' | 'thriving' | 'strained' | 'insolvent';

/**
 * A progression tier. The table is data driven: new tiers are added by
 * extending this list, no engine code has to change.
 */
export interface CorporationTier {
  id: CorporationTierId;
  level: number;
  name: string;
  /** Maximum number of employees the corporation may employ. */
  employeeCapacity: number;
  /** Multiplier applied to the revenue generated by the workforce. */
  revenueFactor: number;
  /** Multiplier applied to the operating costs. */
  operatingCostFactor: number;
  /** Departments the corporation may staff at this tier. */
  availableDepartments: DepartmentId[];
  /** Minimum lifetime revenue required to reach this tier. */
  requiredLifetimeRevenue: number;
  /** Minimum reputation required to reach this tier. */
  requiredReputation: number;
  /** Minimum number of employees required to reach this tier. */
  requiredEmployeeCount: number;
}

export type TransactionType =
  | 'hiring'
  | 'payroll'
  | 'payroll-missed'
  | 'revenue'
  | 'operating'
  | 'milestone';

export interface CorporationTransaction {
  id: string;
  type: TransactionType;
  /** Signed amount: positive is income, negative is an expense. */
  amount: number;
  description: string;
  /** Cash balance after the transaction was applied. */
  balanceAfter: number;
  /** Simulated time the transaction was recorded at. */
  simTimeMs: number;
  /** For a missed payroll: the amount that could not be paid. */
  shortfall?: number;
}

/** Aggregated figures of one completed payroll period. */
export interface FinancialSnapshot {
  periodId: string;
  revenue: number;
  operatingExpenses: number;
  payrollExpenses: number;
  netProfit: number;
  balance: number;
  employeeCount: number;
}

export interface CorporationFinances {
  /** Cash available. Never negative. */
  balance: number;
  lifetimeRevenue: number;
  lifetimeOperatingExpenses: number;
  lifetimePayrollExpenses: number;
  lifetimeHiringCosts: number;
  /** Revenue accrued since the last payroll period closed. */
  periodRevenue: number;
  periodOperatingExpenses: number;
  periodPayrollExpenses: number;
}

export interface Corporation {
  id: CorporationId;
  name: string;
  /** Simulated time the corporation was founded (epoch milliseconds). */
  foundedAtSimMs: number;
  tierId: CorporationTierId;
  level: number;
  status: CorporationStatus;
  /** Corporate reputation, 0..100. */
  reputation: number;
  finances: CorporationFinances;
  /** Bounded ledger of the most recent transactions. */
  transactions: CorporationTransaction[];
  /** Bounded history of completed payroll periods. */
  financialHistory: FinancialSnapshot[];
  /**
   * Identifier of the last payroll period that was processed.
   * Guarantees a period is never paid twice.
   */
  lastPayrollPeriodId: string | null;
  /** Number of payroll periods that could not be paid. */
  missedPayrollCount: number;
  /** Sequence used to generate unique, deterministic transaction ids. */
  transactionSequence: number;
}

export interface CorporationState {
  corporations: Corporation[];
  /** The single player corporation, or null before it is established. */
  playerCorporationId: CorporationId | null;
  /** Number of corporation ticks processed. */
  tick: number;
}

